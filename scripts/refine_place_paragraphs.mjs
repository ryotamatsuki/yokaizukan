function parseMarkdownArticles(source) {
  const matches = [...source.matchAll(/^# (.+)$/gm)];
  const articles = [];

  for (let index = 0; index < matches.length; index += 1) {
    const title = matches[index][1].trim();
    if (title.includes('記事原稿集')) {
      continue;
    }

    const start = matches[index].index + matches[index][0].length;
    const end = index + 1 < matches.length ? matches[index + 1].index : source.length;
    const chunk = source.slice(start, end).trim();
    const lines = chunk
      .split(/\r?\n/)
      .map((line) => line.trimEnd())
      .filter((line) => line.trim() !== '---');

    let subtitle = '';
    let current = [];
    const body = [];
    let inReferenceBlock = false;

    for (const line of lines) {
      if (/^##\s+/.test(line)) {
        const heading = line.replace(/^##\s+/, '').trim();
        if (!subtitle) {
          subtitle = heading;
        }
        inReferenceBlock = heading.includes('参考');
        flush();
        continue;
      }

      if (inReferenceBlock) {
        continue;
      }

      if (!line.trim()) {
        flush();
        continue;
      }

      current.push(line.trim());
    }

    flush();
    articles.push({ title, subtitle, body });

    function flush() {
      if (current.length > 0) {
        body.push(current.join(' '));
        current = [];
      }
    }
  }

  return articles;
}
